// 安装 git 钩子：提交前跑一次静态检查（类型 + strict json_schema 联合类型拦截）。
// 用法：node scripts/install-git-hooks.mjs
// 只用 Node 内置模块，不依赖 husky；钩子文件写在 .git/hooks/pre-commit。
// 钩子内容保持纯 ASCII，避免 Windows 上不同 shell / 编码把中文注释读花。
import { chmodSync, existsSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { execSync } from 'node:child_process'

const root = execSync('git rev-parse --show-toplevel', { encoding: 'utf8' }).trim()
const hooksDir = join(root, '.git', 'hooks')
if (!existsSync(hooksDir)) {
  console.error('Cannot find .git/hooks - run `git init` in this directory first.')
  process.exit(1)
}

const hook = `#!/bin/sh
# Generated by scripts/install-git-hooks.mjs - runs static checks before each commit.
# Bypass once with: git commit --no-verify
echo "[pre-commit] npm run verify"
npm run verify
if [ $? -ne 0 ]; then
  echo "[pre-commit] checks failed - commit aborted (use --no-verify to skip)"
  exit 1
fi
`

const target = join(hooksDir, 'pre-commit')
writeFileSync(target, hook, 'utf8')
try {
  chmodSync(target, 0o755)
} catch {
  /* Windows: chmod is a no-op, git still runs the hook via sh */
}
console.log('[hooks] pre-commit installed ->', target)
